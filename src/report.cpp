std::string BuildCSource(const Policy& policy, const CompiledFilter& startup,
                         const CompiledFilter& runtime,
                         const ReportOptions& options) {
  std::ostringstream out;
  const std::string arch(ArchName(options.arch));
  out << "/* Generated by sctrace.  Do not edit; change the policy and\n"
      << " * regenerate instead.\n"
      << " *\n"
      << " * Target architecture: " << arch << "\n"
      << " * Syscalls allow-listed: " << runtime.allowed.size() << " runtime, "
      << startup.allowed.size() << " startup\n"
      << " *\n"
      << " * Usage:\n"
      << " *   1. call sctrace_install_startup_filter() before the program does\n"
      << " *      anything it does not trust;\n"
      << " *   2. call sctrace_install_runtime_filter() once initialisation is\n"
      << " *      complete.\n"
      << " *\n"
      << " * Both calls need PR_SET_NO_NEW_PRIVS (set here) and a kernel with\n"
      << " * CONFIG_SECCOMP_FILTER.  No privileges are required.\n"
      << " */\n\n"
      << "#define _GNU_SOURCE\n"
      << "#include <errno.h>\n"
      << "#include <linux/audit.h>\n"
      << "#include <linux/filter.h>\n"
      << "#include <linux/seccomp.h>\n"
      << "#include <stddef.h>\n"
      << "#include <sys/prctl.h>\n"
      << "#include <sys/syscall.h>\n"
      << "#include <unistd.h>\n\n";

  auto emit_program = [&](const char* name, const CompiledFilter& filter,
                          const char* description) {
    out << "/* " << description << "\n"
        << " * " << filter.instruction_count << " instructions, "
        << filter.allowed.size() << " syscalls allowed. */\n";
    out << "static struct sock_filter " << name << "[] = {\n";
    out << ToCInitializer(filter.program);
    out << "};\n\n";
  };

  emit_program("sctrace_startup_program", startup,
               "Start-up filter: installed before initialisation.");
  emit_program("sctrace_runtime_program", runtime,
               "Runtime filter: installed once the service is ready.");

  out << "static int sctrace_install(struct sock_filter *program, size_t count,\n"
      << "                            const char *what) {\n"
      << "  struct sock_fprog prog;\n"
      << "  prog.len = (unsigned short)count;\n"
      << "  prog.filter = program;\n"
      << "  if (prctl(PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) != 0) {\n"
      << "    return -1;\n"
      << "  }\n"
      << "  if (syscall(SYS_seccomp, SECCOMP_SET_MODE_FILTER, 0, &prog) != 0) {\n"
      << "    /* ENOSYS: kernel without seccomp filter support; EINVAL: the\n"
      << "     * program was rejected by the verifier.  Either way, do not\n"
      << "     * continue as if the filter were installed. */\n"
      << "    (void)what;\n"
      << "    return -1;\n"
      << "  }\n"
      << "  return 0;\n"
      << "}\n\n"
      << "int sctrace_install_startup_filter(void) {\n"
      << "  return sctrace_install(sctrace_startup_program,\n"
      << "                         sizeof(sctrace_startup_program) /\n"
      << "                             sizeof(sctrace_startup_program[0]),\n"
      << "                         \"startup\");\n"
      << "}\n\n"
      << "int sctrace_install_runtime_filter(void) {\n"
      << "  return sctrace_install(sctrace_runtime_program,\n"
      << "                         sizeof(sctrace_runtime_program) /\n"
      << "                             sizeof(sctrace_runtime_program[0]),\n"
      << "                         \"runtime\");\n"
      << "}\n";
  (void)policy;
  (void)options;
  return out.str();
}

