std::string BuildPolicyGuide(const Policy& policy, const CompiledFilter& startup,
                             const CompiledFilter& runtime,
                             const VerificationResult& verification,
                             const GenerationResult* generation,
                             const ReportOptions& options) {
  std::ostringstream out;
  const std::string arch(ArchName(options.arch));

  out << "# seccomp policy: " << (policy.name.empty() ? "unnamed" : policy.name)
      << "\n\n";
  out << "Generated by `sctrace` for **" << arch << "**.  ";
  out << "Read this document before installing the filter: it lists every "
         "syscall the service is allowed to make, every restriction on their "
         "arguments, and what was verified against the trace.\n\n";

  // ---------------------------------------------------------------- summary
  out << "## Summary\n\n";
  out << "| Metric | Startup | Runtime |\n|---|---|---|\n";
  out << "| Allowed syscalls | " << startup.allowed.size() << " | "
      << runtime.allowed.size() << " |\n";
  out << "| Argument-restricted syscalls | " << startup.restricted.size() << " | "
      << runtime.restricted.size() << " |\n";
  out << "| BPF instructions | " << startup.instruction_count << " | "
      << runtime.instruction_count << " |\n";
  out << "| Default verdict | " << ActionCell(policy.default_action) << " | "
      << ActionCell(policy.default_action) << " |\n\n";

  if (options.trace_path.empty()) {
    out << "The policy was written by hand, not generated from a trace.\n\n";
  } else {
    out << "Trace: `" << options.trace_path << "`";
    if (!options.binary_name.empty()) {
      out << " (binary `" << options.binary_name << "`)";
    }
    out << ".\n\n";
  }

  // ------------------------------------------------------------- how it works
  out << "## How the filter works\n\n";
  out << "Two filters are installed:\n\n";
  out << "1. **Startup filter**, installed before `execve` finishes.  It admits "
         "the start-up calls and, deliberately, everything the runtime filter "
         "will also admit.  It has to: several threads share the process, and "
         "one of them can reach the ready point before the second filter is "
         "installed on it.\n";
  out << "2. **Runtime filter**, installed once the program signals it is "
         "ready ("
      << (options.phase_options.ready_syscall.empty()
              ? std::string("automatically detected")
              : "`" + options.phase_options.ready_syscall + "`")
      << ").  From that point only the runtime rules apply, so the long-lived "
         "filter is as small as the steady state allows.\n\n";
  out << "Both filters begin with an architecture check: a syscall made through "
         "another ABI (the 32-bit compat entry on x86_64, for example) has a "
         "different numbering and is killed rather than misinterpreted.  "
         "Anything the policy does not mention gets the default verdict, "
      << ActionCell(policy.default_action) << ".\n\n";

  // --------------------------------------------------------------- allowed
  out << "## What is allowed\n\n";
  auto section = [&](const char* title, const CompiledFilter& filter) {
    out << "### " << title << "\n\n";
    auto grouped = GroupForReport(filter.allowed);
    if (grouped.empty()) {
      out << "_Nothing is allowed in this phase._\n\n";
      return;
    }
    out << MarkdownTableHeader({"Group", "Syscalls"});
    for (const auto& [group, members] : grouped) {
      out << "| `" << group << "` | " << SyscallList(members) << " |\n";
    }
    out << "\n";
  };
  section("Startup", startup);
  section("Runtime", runtime);

  // ------------------------------------------------------------ restrictions
  out << "## Argument-level restrictions\n\n";
  out << "These rules do more than allow a syscall: the kernel's BPF program "
         "inspects the arguments and denies the call when they do not match.  "
         "This is what turns \"the service may call `socket()`\" into \"the "
         "service may create an `AF_INET` socket\".\n\n";
  auto restrictions = [&](const char* title, const CompiledFilter& filter) {
    out << "### " << title << "\n\n";
    if (filter.restricted.empty()) {
      out << "_No argument restrictions in this phase._\n\n";
      return;
    }
    out << MarkdownTableHeader({"Syscall", "Verdict", "Condition", "Observed"});
    for (const auto& restriction : filter.restricted) {
      std::string why;
      if (generation) {
        auto it = generation->observed_arguments.find(restriction.syscall);
        if (it != generation->observed_arguments.end()) {
          why = Join(it->second, "; ");
        }
      }
      if (why.empty()) why = "stated in the policy";
      for (const auto& clause : restriction.clauses) {
        out << "| `" << restriction.syscall << "` | `" << clause.verdict
            << "` | " << MarkdownEscape(clause.condition) << " | "
            << MarkdownEscape(why) << " |\n";
      }
    }
    out << "\n";
  };
  restrictions("Startup", startup);
  restrictions("Runtime", runtime);

  // ---------------------------------------------------------------- denied
  out << "## What is explicitly denied\n\n";
  auto denied = [&](const CompiledFilter& filter) {
    std::set<std::string> seen;
    std::ostringstream rows;
    for (const auto& [syscall, action] : filter.denied) {
      std::string key = syscall + " " + action.ToString();
      if (!seen.insert(key).second) continue;
      rows << "| `" << syscall << "` | " << ActionCell(action) << " |\n";
    }
    return rows.str();
  };
  std::string deny_rows = denied(startup);
  if (deny_rows.empty()) {
    out << "No syscall is denied by name.  Calls not listed above are still "
           "rejected by the default verdict.\n\n";
  } else {
    out << MarkdownTableHeader({"Syscall", "Verdict"});
    out << deny_rows << "\n";
  }

  // ------------------------------------------------------------ verification
  out << "## Verification against the trace\n\n";
  out << "Each recorded call was replayed through the generated BPF program by "
         "an interpreter, and the result compared with the policy's own "
         "semantics (a second, independent evaluation of the rules).  A "
         "disagreement would mean the compiler and the policy text have "
         "diverged.\n\n";
  out << MarkdownTableHeader({"Phase", "Calls", "Allowed", "Denied", "Intended denials"});
  out << "| Startup | " << verification.startup.calls << " | "
      << verification.startup.allowed << " | " << verification.startup.denied
      << " | " << verification.startup.intended_denials << " |\n";
  out << "| Runtime | " << verification.runtime.calls << " | "
      << verification.runtime.allowed << " | " << verification.runtime.denied
      << " | " << verification.runtime.intended_denials << " |\n\n";

  if (verification.ok) {
    out << "**Result: every recorded call is handled as the policy intends.**\n\n";
  } else {
    out << "**Result: the filter and the policy disagree.**  Details below; do "
           "not install this filter until they are resolved.\n\n";
    for (const std::string& error : verification.errors) {
      out << "- " << MarkdownEscape(error) << "\n";
    }
    out << "\n";
  }
  if (!verification.warnings.empty()) {
    out << "Warnings:\n\n";
    for (const std::string& warning : verification.warnings) {
      out << "- " << MarkdownEscape(warning) << "\n";
    }
    out << "\n";
  }

  // --------------------------------------------------------------- processes
  if (!verification.processes.empty()) {
    out << "## Processes in the trace\n\n";
    out << "Threads are listed separately because strace reports them by tid; "
           "they share the process's filter.  A forked child inherits the "
           "filter its parent had installed at the time of the fork, which is "
           "why one policy covers every process in the trace.  The `denied` "
           "column counts calls the filter blocks.\n\n";
    out << MarkdownTableHeader({"pid", "kind", "created by", "calls", "denied"});
    for (const auto& proc : verification.processes) {
      std::string kind = proc.is_thread ? "thread"
                         : proc.is_forked_child ? "forked child"
                                                : "process";
      std::string origin = proc.created_by_syscall.empty()
                               ? "-"
                               : proc.created_by_syscall + " (" +
                                     std::to_string(proc.created_by_pid) + ")";
      out << "| " << proc.pid << " | " << kind << " | " << origin << " | "
          << proc.calls << " | " << proc.denials << " |\n";
    }
    out << "\n";
  } else if (generation && !generation->processes.empty()) {
    out << "## Processes in the trace\n\n";
    out << MarkdownTableHeader({"pid", "kind", "created by", "startup calls",
                                "runtime calls"});
    for (const auto& proc : generation->processes) {
      std::string kind = proc.is_thread ? "thread"
                         : proc.is_forked_child ? "forked child"
                                                : "process";
      std::string origin = proc.created_by_syscall.empty()
                               ? "-"
                               : proc.created_by_syscall + " (" +
                                     std::to_string(proc.created_by_pid) + ")";
      out << "| " << proc.pid << " | " << kind << " | " << origin << " | "
          << proc.startup_calls << " | " << proc.runtime_calls << " |\n";
    }
    out << "\n";
  }

  // --------------------------------------------------------------- generation
  if (generation) {
    out << "## How this policy was derived\n\n";
    out << "- " << generation->stats.startup_syscalls
        << " distinct syscalls appeared before the ready point, "
        << generation->stats.runtime_syscalls << " after it; "
        << generation->stats.both << " appeared in both phases and are allowed "
        << "in both.\n";
    out << "- " << generation->stats.argument_restrictions
        << " arguments were constrained from observed values.\n";
    if (!generation->stats.notes.empty()) {
      out << "\nArguments that were left unconstrained, and why:\n\n";
      for (const std::string& note : generation->stats.notes) {
        out << "- " << MarkdownEscape(note) << "\n";
      }
    }
    if (!generation->stats.warnings.empty()) {
      out << "\nGenerator warnings:\n\n";
      for (const std::string& warning : generation->stats.warnings) {
        out << "- " << MarkdownEscape(warning) << "\n";
      }
    }
    out << "\n";
  }

  // --------------------------------------------------------------- limitations
  out << "## Limitations\n\n";
  out << "- The filter sees scalars, not memory.  A path, a `struct sockaddr` "
         "or a `struct clone_args` is only a pointer; the checks that matter "
         "are the ones on integers and flag words.\n";
  out << "- A trace is a sample.  A syscall the service can make on another "
         "code path, under a different configuration, or only on error will "
         "not be in it.  Run the service under load before trusting the "
         "generated policy, and consider starting from the `log` or `trace` "
         "action for a while.\n";
  out << "- Argument values are compared as the 64-bit register values the "
         "kernel sees.  A negative `int` argument arrives sign-extended; the "
         "policy text and the generated comparison agree on that, but a value "
         "written as `-1` means `0xffffffffffffffff`.\n";
  out << "- `SECCOMP_RET_ERRNO` cannot return more than 4095, and `kill` "
         "terminates the whole thread immediately.\n\n";

  // --------------------------------------------------------------- appendix
  if (options.include_disassembly) {
    out << "## Appendix: generated BPF programs\n\n";
    out << "### Startup filter\n\n```\n" << Disassemble(startup.program)
        << "```\n\n";
    out << "### Runtime filter\n\n```\n" << Disassemble(runtime.program)
        << "```\n\n";
  }

  out << "---\n\n";
  out << "Install with the accompanying C file, or adapt it: it contains both "
         "programs as plain `sock_filter` arrays and the two `seccomp()` "
         "calls, so it can be dropped into an existing initialisation path.\n";
  return out.str();
}

