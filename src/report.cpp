std::string MarkdownTableHeader(std::initializer_list<const char*> columns) {
  std::ostringstream out;
  out << "|";
  for (const char* c : columns) out << " " << c << " |";
  out << "\n|";
  for (size_t i = 0; i < columns.size(); ++i) out << "---|";
  out << "\n";
  return out.str();
}

std::string SyscallList(const std::vector<std::string>& names) {
  if (names.empty()) return "_none_";
  std::string out;
  for (size_t i = 0; i < names.size(); ++i) {
    if (i) out += ", ";
    out += "`" + names[i] + "`";
  }
  return out;
}

std::string ActionCell(const Action& action) {
  return "`" + MarkdownEscape(action.ToString()) + "`";
}

// Groups the filter's allowed syscalls by their first argument family so the
// document is skimmable instead of one long list.
std::vector<std::pair<std::string, std::vector<std::string>>> GroupForReport(
    const std::vector<std::string>& names) {
  std::map<std::string, std::vector<std::string>> by_family;
  for (const std::string& name : names) {
    std::string family = "other";
    for (const auto& group : BuiltinGroups()) {
      if (std::find(group.members.begin(), group.members.end(), name) !=
          group.members.end()) {
        family = group.name;
        break;
      }
    }
    by_family[family].push_back(name);
  }
  std::vector<std::pair<std::string, std::vector<std::string>>> out;
  for (auto& [family, members] : by_family) out.emplace_back(family, members);
  return out;
}

