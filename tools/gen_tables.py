def emit_constants(path, consts, audit_x86, audit_arm):
    lines = ["// Generated by tools/gen_tables.py from Linux v6.6 sources.",
             "// Do not edit; rerun the generator instead.", "",
             "// clang-format off",
             "constexpr NamedConstant kConstants[] = {"]
    for name in sorted(consts):
        lines.append('    {"%s", %sLL},' % (name, consts[name]))
    lines.append("};")
    lines.append("constexpr long long kAuditArchX86_64 = %sLL;" % audit_x86)
    lines.append("constexpr long long kAuditArchAarch64 = %sLL;" % audit_arm)
    lines.append("// clang-format on")
    write_if_changed(path, "\n".join(lines) + "\n")


def write_if_changed(path, content):
    old = None
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            old = f.read()
    if old == content:
        return False
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify generated files are up to date")
    args = ap.parse_args()

    sysdir = os.path.join(ROOT, "src")
    sc_path = os.path.join(sysdir, "syscalls_generated.inc")
    co_path = os.path.join(sysdir, "constants_generated.inc")

    x86 = load_x86_64_syscalls()
    arm = load_aarch64_syscalls()
    consts, audit_x86, audit_arm = load_constants()

    print("x86_64 syscalls: %d" % len(set(n for _, n in x86)))
    print("aarch64 syscalls: %d" % len(arm))
    print("constants: %d" % len(consts))
    if len(consts) < 300:
        print("warning: suspiciously few constants extracted", file=sys.stderr)

    if args.check:
        tmp_sc = sc_path + ".tmp"
        tmp_co = co_path + ".tmp"
        emit_syscalls(tmp_sc, x86, arm)
        emit_constants(tmp_co, consts, audit_x86, audit_arm)
        ok = True
        for a, b in ((tmp_sc, sc_path), (tmp_co, co_path)):
            with open(a) as f1, open(b) as f2:
                if f1.read() != f2.read():
                    print("stale: %s (regenerate with tools/gen_tables.py)" % b,
                          file=sys.stderr)
                    ok = False
            os.unlink(a)
        return 0 if ok else 1

    emit_syscalls(sc_path, x86, arm)
    emit_constants(co_path, consts, audit_x86, audit_arm)
    print("wrote %s" % sc_path)
    print("wrote %s" % co_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
