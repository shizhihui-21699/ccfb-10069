def emit_syscalls(path, table_x86, table_arm):
    names = sorted({n for _, n in table_x86} | {n for _, n in table_arm})
    lines = []
    lines.append("// Generated by tools/gen_tables.py from Linux v6.6 sources.")
    lines.append("// Do not edit; rerun the generator instead.")
    lines.append("")
    lines.append("// clang-format off")
    lines.append("constexpr SyscallEntry kSyscallEntries[] = {")
    for name in names:
        x = dict((n, nr) for nr, n in table_x86).get(name, -1)
        a = dict((n, nr) for nr, n in table_arm).get(name, -1)
        lines.append('    {"%s", %d, %d},' % (name, x, a))
    lines.append("};")
    lines.append("// clang-format on")
    write_if_changed(path, "\n".join(lines) + "\n")


