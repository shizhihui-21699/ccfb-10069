def load_x86_64_syscalls():
    path = os.path.join(UAPI, "x86_64", "syscall_64.tbl")
    out = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 3:
                continue
            nr, abi, name = parts[0], parts[1], parts[2]
            if abi not in ("common", "64"):
                continue
            out.append((int(nr), name))
    return out


def load_aarch64_syscalls():
    p = Preprocessor([os.path.join(UAPI, "include"),
                      os.path.join(UAPI, "aarch64"),
                      os.path.join(UAPI, "shims")],
                     predefined={"__BITS_PER_LONG": 64})
    p.process_file(os.path.join(UAPI, "aarch64", "asm", "unistd.h"))
    out = []
    for name, mac in p.macros.items():
        if not name.startswith("__NR_"):
            continue
        if name in ("__NR_syscalls", "__NR_arch_specific_syscall"):
            continue
        v = p.value_of(name)
        if v is None:
            continue
        out.append((int(v), name[len("__NR_"):]))
    # __NR_32764_* aliases resolve to the same numbers; drop duplicates
    seen = {}
    for nr, name in out:
        if nr in seen and seen[nr] != name:
            # prefer the canonical name (the shorter one, e.g. fcntl over
            # fcntl64) - on a 64-bit ABI the 3264 alias is not a real name
            continue
        seen[nr] = name
    return sorted(seen.items())


